const DOC_LABELS: Record<string, string> = {
  'evidence-package.pdf':        'WCAG Technical Evidence Package',
  'developer-guide.pdf':         'Developer Remediation Guide',
  'monitoring-confirmation.pdf': 'Monitoring Activation Confirmation',
}

const DOC_ORDER = [
  'evidence-package.pdf',
  'developer-guide.pdf',
  'monitoring-confirmation.pdf',
]

// ─── Helpers ──────────────────────────────────────────────────────────────────

function scoreColor(score: number): string {
  if (score >= 80) return '#16a34a'   // green
  if (score >= 50) return '#d97706'   // amber
  return '#dc2626'                    // red
}

