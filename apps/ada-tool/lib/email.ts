// ─── Daily cap check ──────────────────────────────────────────────────────────

async function getDailySentCount(): Promise<number> {
  const db    = createServiceClient()
  const today = new Date().toISOString().slice(0, 10)   // YYYY-MM-DD

  const { count } = await db
    .from('email_deliveries')
    .select('*', { count: 'exact', head: true })
    .eq('status', 'sent')
    .gte('sent_at', `${today}T00:00:00.000Z`)
    .lt('sent_at', `${today}T23:59:59.999Z`)

  return count ?? 0
}

// ─── Main export ──────────────────────────────────────────────────────────────

export async function sendPdfDelivery(params: PdfDeliveryParams): Promise<void> {
  const { paymentId, email, tier, pdfUrls } = params
  const db = createServiceClient()

  // Derive filenames by tier (same order as buildPdfsForTier)
  const pdfFilenames = DOC_ORDER.filter((_, i) => i < pdfUrls.length)

  try {
    // ── Daily cap guard ───────────────────────────────────────────────────────
    const dailyCount = await getDailySentCount()
    if (dailyCount >= RESEND_DAILY_CAP) {
      console.error(`Resend daily cap reached (${dailyCount}/${RESEND_DAILY_CAP}). Email NOT sent for payment ${paymentId}.`)
      await db
        .from('email_deliveries')
        .update({ status: 'failed' })
        .eq('payment_id', paymentId)
      return
    }
    if (dailyCount >= RESEND_DAILY_WARN) {
      console.warn(`Resend daily count at ${dailyCount}/${RESEND_DAILY_CAP} — approaching limit.`)
    }

    // ── Send via Resend ───────────────────────────────────────────────────────
    const resend = new Resend(process.env.RESEND_API_KEY)
    const fromEmail = process.env.RESEND_FROM_EMAIL ?? 'onboarding@resend.dev'

    const { error } = await resend.emails.send({
      from:    `ADA Evidence Tool <${fromEmail}>`,
      to:      email,
      subject: 'Your WCAG Technical Evidence Package is ready',
      html:    buildHtml(params, pdfFilenames),
    })

    if (error) {
      throw new Error(`Resend error: ${error.message}`)
    }

    // ── Mark as sent ──────────────────────────────────────────────────────────
    const { error: updateError } = await db
      .from('email_deliveries')
      .update({ status: 'sent', sent_at: new Date().toISOString() })
      .eq('payment_id', paymentId)

    if (updateError) {
      console.error('email_deliveries update to sent failed:', updateError)
    }

  } catch (err) {
    // Non-fatal: log and mark failed — caller (webhook) still returns 200
    console.error(`sendPdfDelivery failed for payment ${paymentId}:`, err)

    await db
      .from('email_deliveries')
      .update({ status: 'failed' })
      .eq('payment_id', paymentId)
      .then(({ error }) => {
        if (error) console.error('email_deliveries update to failed:', error)
      })
  }
}
